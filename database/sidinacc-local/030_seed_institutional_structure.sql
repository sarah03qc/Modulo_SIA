    SET IDENTITY_INSERT dbo.CAF_CAT_OFICINA_LOCAL ON;
    INSERT INTO dbo.CAF_CAT_OFICINA_LOCAL (CAT_idOficinaLocal, CAT_idRegion, OFL_nombre, OFL_descripcion, BIT_eliminado)
