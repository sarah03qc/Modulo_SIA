                               AND CONVERT(nvarchar(250), t.EST_descripcion) COLLATE Latin1_General_BIN2 = s.EST_descripcion COLLATE Latin1_General_BIN2
                               AND ISNULL(t.BIT_eliminado, 0) = 0));
