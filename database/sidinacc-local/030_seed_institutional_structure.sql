    FROM @ofl s
    WHERE NOT EXISTS (SELECT 1 FROM dbo.CAF_CAT_OFICINA_LOCAL t WHERE t.CAT_idOficinaLocal = s.CAT_idOficinaLocal);
    SET IDENTITY_INSERT dbo.CAF_CAT_OFICINA_LOCAL OFF;

